-- The schema of SQLite migrations 001-006, in one step. New migrations get a file in each folder.
CREATE TABLE channel (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    avatar_url TEXT,
    uploads_playlist_id TEXT NOT NULL,
    connected_at TEXT NOT NULL
);

CREATE TABLE videos (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    category_id TEXT NOT NULL,
    tags_json TEXT NOT NULL,
    default_language TEXT,
    default_audio_language TEXT,
    published_at TEXT NOT NULL,
    duration_s INTEGER NOT NULL,
    privacy_status TEXT NOT NULL,
    thumbnail_url TEXT,
    is_short INTEGER,           -- NULL until classified
    short_source TEXT,          -- probe | duration | manual
    synced_at TEXT NOT NULL,
    last_edited_run_id INTEGER
);
CREATE INDEX videos_published_at ON videos (published_at DESC);

CREATE TABLE quota_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts TEXT NOT NULL,
    pt_date TEXT NOT NULL,
    method TEXT NOT NULL,
    units INTEGER NOT NULL,
    run_id INTEGER
);
CREATE INDEX quota_events_pt_date ON quota_events (pt_date);

CREATE TABLE settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE changesets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL,
    operation_json TEXT NOT NULL,
    requested INTEGER NOT NULL,     -- how many Video ids the owner selected
    status TEXT NOT NULL CHECK (status IN ('draft', 'discarded', 'applied'))
);

CREATE TABLE changeset_items (
    changeset_id INTEGER NOT NULL REFERENCES changesets (id),
    video_id TEXT NOT NULL,
    seq INTEGER NOT NULL,
    title TEXT NOT NULL,
    before_description TEXT NOT NULL,
    computed_description TEXT NOT NULL,
    override_description TEXT,      -- hand edit, if any
    changed INTEGER NOT NULL,
    included INTEGER NOT NULL,
    flags_json TEXT NOT NULL,
    computed_flags_json TEXT,       -- the Operation's own verdict, kept so an Override can be reset to it
    PRIMARY KEY (changeset_id, video_id)
);

CREATE TABLE runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('apply', 'restore')),
    changeset_id INTEGER REFERENCES changesets (id),
    source_run_id INTEGER REFERENCES runs (id),
    status TEXT NOT NULL CHECK (status IN
        ('pending', 'running', 'paused', 'paused_quota', 'interrupted', 'cancelled', 'completed')),
    created_at TEXT NOT NULL,
    started_at TEXT,
    finished_at TEXT,
    control TEXT CHECK (control IN ('pause', 'cancel'))  -- a Pause/Cancel the engine acts on between Videos
);

CREATE TABLE run_items (
    run_id INTEGER NOT NULL REFERENCES runs (id),
    video_id TEXT NOT NULL,
    seq INTEGER NOT NULL,
    title TEXT NOT NULL,
    expected_before TEXT NOT NULL,     -- the description the owner reviewed
    target_description TEXT NOT NULL,
    backup_snippet_json TEXT,          -- the live snippet, saved before the Run's first write
    status TEXT NOT NULL CHECK (status IN
        ('pending', 'success', 'failed', 'stale', 'blocked', 'noop', 'cancelled')),
    attempts INTEGER NOT NULL DEFAULT 0,
    error TEXT,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (run_id, video_id)
);

CREATE TABLE run_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES runs (id),
    ts TEXT NOT NULL,
    level TEXT NOT NULL,
    message TEXT NOT NULL
);
